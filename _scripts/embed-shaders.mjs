import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const upstream = join(root, 'packages/lge-core/src/shaders/upstream');

const files = {
  WGSL_VERTEX: 'vertex.wgsl',
  WGSL_MAIN: 'fragment-main.wgsl',
  WGSL_BG: 'fragment-bg.wgsl',
  WGSL_VBLUR: 'fragment-bg-vblur.wgsl',
  WGSL_HBLUR: 'fragment-bg-hblur.wgsl',
  WGSL_COLOR_LIB: 'lib/color.wgsl',
  WGSL_MATH_LIB: 'lib/math.wgsl',
  WGSL_SDF_LIB: 'lib/sdf.wgsl',
  GLSL_VERTEX: 'glsl/vertex.glsl',
  GLSL_MAIN: 'glsl/fragment-main.glsl',
  GLSL_BG: 'glsl/fragment-bg.glsl',
  GLSL_VBLUR: 'glsl/fragment-bg-vblur.glsl',
  GLSL_HBLUR: 'glsl/fragment-bg-hblur.glsl',
  GLSL_COLOR_LIB: 'glsl/lib/color.glsl',
  GLSL_MATH_LIB: 'glsl/lib/math.glsl',
  GLSL_SDF_LIB: 'glsl/lib/sdf.glsl',
};

const escapeTemplate = (source) =>
  source.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');

const lines = [
  '// AUTO-GENERATED by _scripts/embed-shaders.mjs — do not edit by hand.',
  '// Source shaders are MIT, Copyright (c) 2024 Charles Yin.',
  '',
];

for (const [name, relativePath] of Object.entries(files)) {
  const source = readFileSync(join(upstream, relativePath), 'utf8').replace(/\r\n/g, '\n');
  lines.push(`export const ${name} = \`${escapeTemplate(source)}\`;`, '');
}

const output = join(root, 'packages/lge-core/src/shaders/generated.ts');
writeFileSync(output, `${lines.join('\n')}\n`, 'utf8');
console.log(`Embedded ${Object.keys(files).length} shaders -> ${output}`);
